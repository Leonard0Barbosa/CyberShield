#Fase 4 — Internet e Links

'''Pergunta: Qual sinal indica maior probabilidade de um site ser uma tentativa de golpe?

A) Site usando HTTPS ❌

Por que está errada: O HTTPS apenas criptografa o tráfego entre você e o site. Golpistas também podem usar HTTPS em sites falsos.

💡 Dica: HTTPS garante conexão cifrada, não a honestidade do dono do site.

B) Site carregando imagens lentamente ❌

Por que está errada: Lentidão é um problema de desempenho/conexão, não um indicador direto de fraude.

C) Domínio diferente do domínio oficial da empresa ✅

Por que está correta: Golpistas registram nomes parecidos (ex: banc0-oficial.com) para enganar o usuário.

D) Site contendo muitas imagens ❌

Por que está errada: Design e quantidade de mídias não definem a legitimidade de um endereço.

💡 Dica: Sempre confira a barra de endereço do navegador.'''

