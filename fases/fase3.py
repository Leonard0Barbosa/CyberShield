#Fase 3 — Engenharia Social (Phishing)

'''Pergunta: Você recebe um e-mail urgente pedindo login através de um link. O que deve fazer primeiro?

A) Clicar rapidamente para evitar o bloqueio ❌

Por que está errada: O senso de urgência é a principal gatilho psicológico usado em ataques de Phishing.

💡 Dica: Desconfie imediatamente de mensagens que exigem ação desesperada.

B) Responder pedindo a senha do remetente ❌

Por que está errada: Não valida a identidade do remetente e expõe você ainda mais ao atacante.

💡 Dica: Nunca use o próprio e-mail suspeito para tentar validar a mensagem.

C) Verificar remetente, endereço e contexto da mensagem ✅

Por que está correta: Analisar o endereço real de envio, os links e a coerência do texto evita cair em golpes.

D) Encaminhar para todos os colegas ❌

Por que está errada: Pode espalhar o link malicioso dentro da rede da empresa.

💡 Dica: Notifique a equipe de segurança/TI em vez de reencaminhar.'''