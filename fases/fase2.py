#Fase 2 — Senhas & Proteção

'''Pergunta: Qual medida reduz melhor o risco de comprometimento de uma conta?

A) Trocar a senha toda semana por uma curta ❌

Por que está errada: Senhas curtas são fáceis de quebrar por força bruta. A frequência de troca não compensa a fraqueza da senha.

💡 Dica: Priorize tamanho e complexidade antes de pensar em trocas frequentes.

B) Usar a mesma senha em vários serviços ❌

Por que está errada: Gera o efeito dominó: se um serviço vazar, todas as suas outras contas serão invadidas.

💡 Dica: Nunca reutilize senhas em serviços importantes.

C) Usar senha exclusiva e MFA ✅

Por que está correta: A senha única isola o risco e a Autenticação Multifator (MFA) adiciona uma segunda camada física/digital de validação.

D) Escrever a senha em um arquivo chamado "senhas.txt" ❌

Por que está errada: Arquivos em texto puro são alvos fáceis para malwares e pessoas não autorizadas.

💡 Dica: Para armazenar senhas com segurança, utilize um Gerenciador de Senhas.'''
